def _imported_first_party_modules(node: ast.AST) -> list[str]:
    """Return every ``app.*`` module named by one AST import node."""
    if isinstance(node, ast.ImportFrom):
        if node.level == 0 and node.module and node.module.startswith("app"):
            return [node.module]
        return []
    if isinstance(node, ast.Import):
        return [alias.name for alias in node.names if alias.name.startswith("app")]
    return []


def _module_to_relative_path(module: str, *, service_root: Path) -> str | None:
    parts = module.split(".")
    candidate = Path(*parts).with_suffix(".py")
    if (service_root / candidate).is_file():
        return candidate.as_posix()
    candidate = Path(*parts, "__init__.py")
    if (service_root / candidate).is_file():
        return candidate.as_posix()
    return None


def signal_decision_import_closure(
    *,
    roots: Iterable[str],
    service_root: Path = _SERVICE_ROOT,
) -> set[str]:
    """Return the transitive first-party (``app.``) import closure of ``roots``.

    Walks the full AST — including deferred, function-local imports — so a
    closure member reached only inside a function (e.g. the
    ``app.lean_sidecar.trading_calendar`` import inside
    ``app/engine/live/indicator_state.py``) is still counted: a deferred
    import still executes, and its bytes still ship.
    """
    seen: set[str] = set()
    frontier = list(roots)
    while frontier:
        relative = frontier.pop()
        if relative in seen:
            continue
        seen.add(relative)
        source = (service_root / relative).read_text(encoding="utf-8")
        tree = ast.parse(source, filename=relative)
        for node in ast.walk(tree):
            for module in _imported_first_party_modules(node):
                member = _module_to_relative_path(module, service_root=service_root)
                if member is not None and member not in seen:
                    frontier.append(member)
    return seen


class QualificationFailedError(RuntimeError):
    """A program's golden-trace qualification suite did not pass."""


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="run_signal_program_build_qualification",
        description=(
            "Run each registered Signal Program's golden-trace qualification suite and, "
            "only on a pass, emit its build receipt into the committed manifest."
        ),
    )
    parser.add_argument("--manifest-path", type=Path, default=DEFAULT_QUALIFICATION_MANIFEST)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed manifest differs from a freshly qualified run.",
    )
    parser.add_argument(
        "--qualified-at-ms",
        type=int,
        default=None,
        help=(
            "Timestamp stamped on a brand-new receipt. Defaults to now. Ignored for any "
            "program whose qualified identity is unchanged from the committed manifest."
        ),
    )
    return parser.parse_args(argv)


def _run_qualification_suite(test_ref: str) -> None:
    """Run one pytest node id; raise with captured output on any non-zero exit."""
    command = [sys.executable, "-m", "pytest", "-q", test_ref]
    try:
        completed = subprocess.run(
            command,
            cwd=_SERVICE_ROOT,
            check=False,
            capture_output=True,
            text=True,
            timeout=_PYTEST_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired as exc:
        raise QualificationFailedError(
            f"golden-trace qualification timed out after {_PYTEST_TIMEOUT_SECONDS}s: {test_ref}"
        ) from exc
    except OSError as exc:
        raise QualificationFailedError(f"could not execute pytest for {test_ref}: {exc}") from exc
    if completed.returncode != 0:
        raise QualificationFailedError(
            f"golden-trace qualification failed for {test_ref} (exit {completed.returncode}); "
            f"stdout tail: {completed.stdout[-2000:]}; stderr tail: {completed.stderr[-2000:]}"
        )


# The identity a receipt's timestamp is earned against. Changing any of these
# is what mints a fresh ``qualified_at_ms``; everything else about a receipt
# can be reshaped without re-dating it.
_QUALIFIED_IDENTITY_FIELDS = (
    "program_key",
    "program_version",
    "golden_trace_root",
    "artifact_digest",
    "qualification_suite",
)


def _prior_qualified_at_ms(path: Path) -> dict[tuple[str, ...], int]:
    """Map each already-qualified identity to the timestamp it earned.

    Reads the committed manifest as raw JSON rather than through
    ``ProgramBuildQualificationManifest``. The only thing wanted here is the
    prior timestamp for an unchanged identity, and parsing through the model
    would couple timestamp reuse to the *current* receipt schema — so a schema
    bump would re-date every receipt, which is exactly the churn the reuse
    rule exists to prevent (issue #1735 bumps it to v2). A receipt missing any
    identity field simply does not match, and mints a fresh timestamp.

    A corrupt manifest still raises: silently re-dating every receipt because
    the file could not be parsed is the failure this whole job exists to
    prevent.
    """
    if not path.is_file():
        return {}
    payload = json.loads(path.read_text(encoding="utf-8"))
    index: dict[tuple[str, ...], int] = {}
    for receipt in payload.get("receipts", ()):
        identity = tuple(receipt.get(field) for field in _QUALIFIED_IDENTITY_FIELDS)
        stamp = receipt.get("qualified_at_ms")
        if any(part is None for part in identity) or not isinstance(stamp, int):
            continue
        index[identity] = stamp
    return index


def qualify_signal_program_builds(
    *,
    prior_qualified_at_ms: dict[tuple[str, ...], int],
    fresh_qualified_at_ms: int,
) -> dict[str, Any]:
    """Run every registered qualification suite and assemble the build-receipt manifest.

    Raises ``QualificationFailedError`` before returning anything if any
    program's suite fails — a behavior change without a matching
    program/root update is caught here, not silently admitted later at
    Start/Resume.
    """
    receipts: list[dict[str, Any]] = []
    for program_key in sorted(_QUALIFICATION_SUITES):
        registration = _STRATEGY_REGISTRY.get(program_key)
        contract = registration.signal_program_contract if registration is not None else None
        if registration is None or contract is None or registration.signal_program_factory is None:
            raise QualificationFailedError(
                f"{program_key} is listed in _QUALIFICATION_SUITES but is not a registered "
                "Signal Program (missing signal_program_contract or signal_program_factory)"
            )
        qualification_suite = _QUALIFICATION_SUITES[program_key]
        _run_qualification_suite(qualification_suite)
        identity = (
            program_key,
            contract.program_version,
            contract.golden_trace_root,
            running_artifact_digest(contract),
            qualification_suite,
        )
        qualified_at_ms = prior_qualified_at_ms.get(identity, fresh_qualified_at_ms)
        receipts.append(
            qualification_receipt_payload(
                program_key=program_key,
                contract=contract,
                qualified_at_ms=qualified_at_ms,
                qualification_suite=qualification_suite,
            )
        )
    return {"schema_version": 2, "receipts": receipts}


def _manifest_text(manifest: dict[str, Any]) -> str:
    """Round-trip through the shared schema, then format exactly like the committed file."""
    ProgramBuildQualificationManifest.model_validate(manifest)
    return json.dumps(manifest, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    prior_qualified_at_ms = _prior_qualified_at_ms(args.manifest_path)
    fresh_qualified_at_ms = (
        args.qualified_at_ms if args.qualified_at_ms is not None else now_ms_utc()
    )

    try:
        manifest = qualify_signal_program_builds(
            prior_qualified_at_ms=prior_qualified_at_ms,
            fresh_qualified_at_ms=fresh_qualified_at_ms,
        )
    except QualificationFailedError as exc:
        sys.stderr.write(f"{exc}\n")
        return 1

    text = _manifest_text(manifest)

    if args.check:
        current = args.manifest_path.read_text(encoding="utf-8") if args.manifest_path.is_file() else None
        if current == text:
            sys.stdout.write(f"{args.manifest_path} is up to date.\n")
            return 0
        sys.stderr.write(
            f"{args.manifest_path} is stale; regenerate with:\n"
            "  python -m scripts.run_signal_program_build_qualification\n"
        )
        return 1

    atomic_write_bytes(args.manifest_path, text.encode("utf-8"))
    sys.stdout.write(f"Wrote {len(manifest['receipts'])} build receipt(s) to {args.manifest_path}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
