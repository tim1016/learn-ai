"""Run the golden-trace qualification job and emit Signal Program build receipts.

PRD `docs/prds/sealed-signal-program-to-governed-alpaca-bot.md` S11.4 requires
that Start and Resume load "a compatibility receipt generated by the
golden-trace qualification job" and states plainly that "CI failure alone is
not an admission control." Before this command existed,
``app/data/signal_program_build_receipts.json`` was hand-authored: nothing
actually re-ran the golden corpus before a receipt was stamped, so a program
edit that forgot to bump ``program_version``/``golden_trace_root`` could still
end up with a committed receipt that looked legitimate.

This command closes that gap. For every registered Signal Program listed in
``_QUALIFICATION_SUITES`` it:

1. runs that program's golden-trace qualification pytest as a subprocess —
   the same test that replays the validated-settings corpus and pins its
   trace root (``tests/engine/strategy/test_ema_signal_program.py``); and
2. only on a clean pass, hashes the currently loaded artifact bytes
   (``app.services.signal_program_admission.running_artifact_digest``) and
   emits a receipt binding that digest to the registry's sealed
   ``(program_version, golden_trace_root)``.

A qualification failure raises before any receipt is written or updated, so a
behavior change without the matching version/root bump cannot produce
admissible runtime evidence — it leaves the prior, now digest-mismatched
receipt in place, and ``prove_running_program_build`` fails closed with
``PROGRAM_BUILD_UNPROVEN`` at Start/Resume.

Usage::

    python -m scripts.run_signal_program_build_qualification
    python -m scripts.run_signal_program_build_qualification --check

Re-running with unchanged code is a byte-for-byte no-op: a receipt whose
(program_key, program_version, golden_trace_root, artifact_digest,
qualification_suite) tuple already matches the committed manifest keeps its
original ``qualified_at_ms`` rather than mint a new one, mirroring the golden
fixture lifecycle rule ("regenerated only with justification").
"""

